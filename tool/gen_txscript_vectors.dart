/// Recomputes the two hardcoded addresses in crypto/txscript/src/standard.rs
/// after the prefix rename. The checksum depends on the prefix, so these
/// cannot be edited by hand.
void main() {
  final pubkey = [
    0x7b, 0xc0, 0x41, 0x96, 0xf1, 0x12, 0x5e, 0x4f, //
    0x26, 0x76, 0xcd, 0x09, 0xed, 0x14, 0xaf, 0xb7, //
    0x72, 0x23, 0xb1, 0xf6, 0x21, 0x77, 0xda, 0x54, //
    0x88, 0x34, 0x63, 0x23, 0xea, 0xa9, 0x1a, 0x69, //
  ];
  final ecdsa = [
    0xba, 0x01, 0xfc, 0x5f, 0x4e, 0x9d, 0x98, 0x79, //
    0x59, 0x9c, 0x69, 0xa3, 0xda, 0xfd, 0xb8, 0x35, //
    0xa7, 0x25, 0x5e, 0x5f, 0x2e, 0x93, 0x4e, 0x93, //
    0x22, 0xec, 0xd3, 0xaf, 0x19, 0x0a, 0xb0, 0xf6, //
    0x0e, //
  ];

  String enc(String prefix, int version, List<int> payload) =>
      bech32Encode(prefix, conv8to5([version, ...payload]));

  print('mainnet PubKey      : ${enc('cen69', 0, pubkey)}');
  print('testnet PubKeyECDSA : ${enc('cen69test', 1, ecdsa)}');
}
